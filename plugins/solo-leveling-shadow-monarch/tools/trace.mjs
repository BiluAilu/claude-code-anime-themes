import potrace from 'potrace'
import { writeFileSync } from 'node:fs'
const SRC = process.argv[2]
const OUT = process.argv[3]
// [export name, file, turdSize, optTolerance, target max dimension or {k: fixed scale}]
const JOBS = [
  ['knightIdle', 'knight-idle', 60, 1.0, { k: 0.45 }], ['knightRaised', 'knight-raised', 60, 1.0, { k: 0.45 }],
  ['knightDash', 'knight-dash', 60, 1.0, { k: 0.45 }], ['knightKneel', 'knight-kneel', 60, 1.0, { k: 0.45 }],
  ['hunterIdle', 'hunter-daggers', 60, 1.0, { k: 0.45 }], ['hunterDash', 'hunter-dash', 60, 1.0, { k: 0.45 }],
  ['soldierSpear', 'soldier-spear', 500, 8.0, 120], ['soldierSword', 'soldier-sword', 500, 8.0, 120], ['soldierBrute', 'soldier-brute', 500, 8.0, 120],
  ['throne', 'throne', 60, 1.0, 460], ['portal', 'portal', 60, 1.2, 460], ['castle', 'castle', 200, 5.0, 700],
  ['sentinel', 'sentinel', 60, 1.2, 420], ['arch', 'pillar-arch', 60, 1.2, 460], ['moon', 'moon', 40, 1.0, 300],
  ['emblem', 'emblem', 400, 8.0, 200], ['wisp1', 'wisp-1', 60, 1.2, 300], ['wisp2', 'wisp-2', 60, 1.2, 300], ['wisp3', 'wisp-3', 60, 1.2, 300],
]
const trace = (f, t, o) => new Promise((res, rej) => potrace.trace(f, { threshold: 128, turdSize: t, optTolerance: o, alphaMax: 1.1, blackOnWhite: true }, (e, s) => e ? rej(e) : res(s)))
let out = '// Generated by tools/trace.mjs from original silhouette art. Do not edit by hand.\nexport type Art = { d: string; w: number; h: number }\nexport const ART = {\n'
let total = 0
for (const [name, file, t, o, maxDim] of JOBS) {
  const small = ['soldier-spear','soldier-sword','soldier-brute','castle','emblem'].includes(file)
  const svg = await trace(`${small ? SRC + '-small' : SRC}/${file}.jpg`, small ? 6 : t, o)
  const d = svg.match(/ d="([^"]+)"/)[1]
  const nums = d.match(/-?\d+\.?\d*/g).map(Number)
  let minX = 1e9, minY = 1e9, maxX = -1e9, maxY = -1e9
  for (let i = 0; i < nums.length; i += 2) { minX = Math.min(minX, nums[i]); maxX = Math.max(maxX, nums[i]); minY = Math.min(minY, nums[i+1]); maxY = Math.max(maxY, nums[i+1]) }
  const k = typeof maxDim === 'object' ? maxDim.k : maxDim / Math.max(maxX - minX, maxY - minY)
  let i = 0
  const body = d.replace(/-?\d+\.?\d*/g, () => { const v = nums[i]; const r = i % 2 === 0 ? (v - minX) * k : (v - minY) * k; i++; return String(Math.round(r)) })
  const compact = body.replace(/,/g, ' ').replace(/\s+/g, ' ').replace(/ ?([MCLZ]) ?/g, '$1').trim()
  const w = Math.round((maxX - minX) * k), h = Math.round((maxY - minY) * k)
  out += `  ${name}: { d: '${compact}', w: ${w}, h: ${h} },\n`
  total += compact.length
  console.log(name.padEnd(13), String(compact.length).padStart(6), `${w}x${h}`)
}
out += '} satisfies Record<string, Art>\n'
writeFileSync(OUT, out)
console.log('total path chars', total)
